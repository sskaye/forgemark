#!/usr/bin/env node
// Bundle the forgemark CLI into the single file the skill ships.
//
// `cli/main.ts` and the app's format layer are compiled by esbuild into
// `assets/forgemark-skill/scripts/forgemark.mjs`: one ESM file, no
// dependencies, runnable by any Node 18+. The bundle is committed, so an
// agent that installs the skill has the tool without a build step; a
// unit test rebuilds it and fails when the committed file is stale, the
// same way skill-bundle.test.ts guards the zip. The same file is
// attached to each GitHub release as `forgemark-cli-<version>.mjs`.
//
// Determinism matters because that test compares bytes: esbuild is
// deterministic for a given input and version, the version is pinned by
// the lockfile, and nothing time- or path-dependent is embedded.
//
// The bundle carries other people's code, so it carries their licence
// notices too: a comment at the end of the file lists every package that
// contributed bytes to it, with its copyright lines, and each distinct
// licence text once. Grouping matters because the skill has a size
// budget (see build-skill.mjs) and five of the packages share the MIT
// text word for word.

import { build } from "esbuild";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const CLI_ENTRY = join(ROOT, "cli", "main.ts");
export const CLI_OUT = join(ROOT, "assets", "forgemark-skill", "scripts", "forgemark.mjs");

// Returns the bundle's bytes; writes them to `outfile` unless `write` is
// false.
export async function buildCli({ outfile = CLI_OUT, write = true } = {}) {
  const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
  const result = await build({
    entryPoints: [CLI_ENTRY],
    outfile,
    absWorkingDir: ROOT,
    bundle: true,
    write: false,
    metafile: true,
    platform: "node",
    format: "esm",
    target: "node18",
    minify: true,
    legalComments: "none",
    logLevel: "silent",
    define: { __FORGEMARK_VERSION__: JSON.stringify(version) },
    // esbuild keeps the entry file's `#!/usr/bin/env node` line first;
    // the banner goes directly under it. The `createRequire` line is the
    // standard shim for bundling CommonJS dependencies (the `yaml`
    // parser calls `require("process")`) into an ES module.
    banner: {
      js:
        `// forgemark ${version} — the Forgemark review-comment CLI. Generated by scripts/build-cli.mjs;\n` +
        `// do not edit. Run with \`node forgemark.mjs --help\`.\n` +
        `// Copyright (c) 2026 sskaye. MIT License: https://github.com/sskaye/forgemark/blob/main/LICENSE\n` +
        `// The notices of the bundled third-party packages are at the end of this file.\n` +
        `import { createRequire as __createRequire } from "node:module";\n` +
        `const require = __createRequire(import.meta.url);`,
    },
  });
  const code = result.outputFiles[0].text;
  const bytes = Buffer.from(code + thirdPartyNotices(result.metafile), "utf8");
  if (write) writeFileSync(outfile, bytes);
  return bytes;
}

// ── third-party notices ───────────────────────────────────────────────

const COPYRIGHT_LINE = /^\s*(copyright\b|\(c\))/i;
// A title line some licence files carry and others don't; it says
// nothing the group heading doesn't.
const TITLE_LINE = /^\s*(the )?(mit|isc) licen[cs]e( \(mit\))?\s*$/i;

function thirdPartyNotices(metafile) {
  // Every package directory that put bytes into the output. A package
  // nested under another (markdown-it's own copy of `entities`) is a
  // separate directory, and listed separately.
  const dirs = new Set();
  for (const output of Object.values(metafile.outputs)) {
    for (const [path, { bytesInOutput }] of Object.entries(output.inputs)) {
      if (bytesInOutput === 0) continue;
      const m = path.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
      if (m) dirs.add(m[1]);
    }
  }

  // Group the packages by licence text, copyright lines aside.
  const groups = new Map();
  for (const dir of [...dirs].sort()) {
    const pkg = JSON.parse(readFileSync(join(ROOT, dir, "package.json"), "utf8"));
    const file = readdirSync(join(ROOT, dir))
      .filter((name) => /^licen[cs]e/i.test(name))
      .sort()[0];
    if (!file) throw new Error(`${dir} has no licence file to carry into the CLI bundle.`);
    const lines = readFileSync(join(ROOT, dir, file), "utf8")
      .replace(/\r\n?/g, "\n")
      .split("\n");
    const copyright = lines.filter((l) => COPYRIGHT_LINE.test(l)).map((l) => l.trim());
    const text = lines
      .filter((l) => !COPYRIGHT_LINE.test(l) && !TITLE_LINE.test(l))
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trim();
    if (text.includes("*/"))
      throw new Error(`${dir}'s licence would end the notice comment early.`);
    const key = text.replace(/\s+/g, " ");
    if (!groups.has(key)) groups.set(key, { license: pkg.license, text, packages: [] });
    groups.get(key).packages.push({ name: pkg.name, version: pkg.version, copyright });
  }

  const sections = [...groups.values()].map((group) => {
    const heading = group.packages
      .map((p) => [`${p.name} ${p.version}`, ...p.copyright.map((c) => `  ${c}`)].join("\n"))
      .join("\n");
    return `${heading}\n\nLicensed under ${group.license}:\n\n${group.text}`;
  });
  return (
    `\n/*! Third-party notices. This file bundles the packages below, each under the licence that follows it.\n\n` +
    sections.join("\n\n----\n\n") +
    `\n*/\n`
  );
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  buildCli()
    .then((bytes) => {
      console.log(`Built CLI bundle (${bytes.length.toLocaleString()} B): ${CLI_OUT}`);
    })
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
